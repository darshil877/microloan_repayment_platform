  function getLang() {
    return localStorage.getItem(LANG_KEY) || "en";
  }

  function setLang(code) {
    localStorage.setItem(LANG_KEY, code);
    apply(code);
  }

  function t(key, params) {
    var lang = getLang();
    var str = (DICT[lang] && DICT[lang][key]) || (DICT.en && DICT.en[key]) || key;
    if (params) {
      Object.keys(params).forEach(function (k) {
        str = str.split("{" + k + "}").join(String(params[k]));
      });
    }
    return str;
  }

  function scriptFor(lang) {
    if (lang === "hi" || lang === "mr" || lang === "mwr") return "devanagari";
    if (lang === "ta") return "tamil";
    if (lang === "te") return "telugu";
    if (lang === "bn") return "bengali";
    return "latin";
  }

  function apply(lang) {
    lang = lang || getLang();
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("data-script", scriptFor(lang));

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      var text = t(key);
      if (text) el.textContent = text;
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      var text = t(key);
      if (text) el.setAttribute("placeholder", text);
    });

    // Update UI language switcher text if present
    var currentSpan = document.getElementById("lang-current");
    if (currentSpan) {
      currentSpan.textContent = lang.toUpperCase();
    }

    document.dispatchEvent(new CustomEvent("i18n:changed", { detail: { lang: lang } }));
  }

  function setupSwitcher() {
    var menu = document.getElementById("lang-menu");
    var toggle = document.getElementById("lang-toggle");

    if (menu) {
      menu.innerHTML = LANGS.map(function (item) {
        return '<button type="button" data-lang="' + item.code + '" class="w-full text-left px-3 py-1.5 rounded-lg text-xs hover:bg-forest/10 font-medium transition flex items-center justify-between cursor-pointer">' +
          '<span>' + item.label + '</span>' +
          '<span class="text-[10px] opacity-50 uppercase">' + item.code + '</span>' +
          '</button>';
      }).join("");

      menu.querySelectorAll("[data-lang]").forEach(function (btn) {
        btn.addEventListener("click", function (e) {
          e.stopPropagation();
          var code = btn.getAttribute("data-lang");
          setLang(code);
          menu.classList.add("hidden");
        });
      });
    }

    if (toggle && menu) {
      toggle.addEventListener("click", function (e) {
        e.stopPropagation();
        menu.classList.toggle("hidden");
      });
      document.addEventListener("click", function () {
        menu.classList.add("hidden");
      });
    }
  }

  global.EquiFlowI18n = {
    LANGS: LANGS,
    getLang: getLang,
    setLang: setLang,
    t: t,
    apply: apply
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () {
      setupSwitcher();
      apply(getLang());
    });
  } else {
    setupSwitcher();
    apply(getLang());
  }
